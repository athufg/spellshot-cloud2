----------------------------------------------------------------------------------------------------- the installer
local saved = {}      -- [a live clip table] = its live { Keys, OffKeys, Both }, while the flame keys are in it

local function restore(clip)
	local s = saved[clip]
	if s then
		clip.Keys, clip.OffKeys, clip.Both = s.Keys, s.OffKeys, s.Both
		saved[clip] = nil
	end
end

-- is the live clip still the one these keys were generated against? (and StanceLegs: no key here names a leg)
local function fits(clip, live)
	local keys = clip.Keys
	return clip.StanceLegs == true and clip.Trigger == live.Trigger and type(keys) == "table" and #keys == live.Keys
		and keys[#keys].t == live.End
end

--- Puts the flame keys into CastPose.Clips (look == "flame") or the live ones back (anything else). Idempotent; safe to
--- call at any time. Returns the list of clip names now on flame keys. opts: see the header.
function T.Apply(CastPose, look, opts)
	local clips = CastPose.Clips
	for _, clip in pairs(clips) do restore(clip) end
	local on = {}
	T.Applied = on
	if look ~= "flame" then return on end
	-- CastPose's OFF_HOLD is a local there, told apart by identity: it is the Off of the live sweep's From key
	local sweep = clips.ScorchingLash
	local hold = sweep and sweep.Keys[1] and sweep.Keys[1].From and sweep.Keys[1].Off
	if not (type(hold) == "table" and next(hold) == nil) then hold = nil end
	local function put(set)
		for name, data in pairs(set) do
			local clip = clips[name]
			local ok = clip ~= nil and fits(clip, data.Live)
			if ok then
				for _, k in ipairs(data.Keys) do
					if k.OffHold then
						if hold then k.Off = hold else ok = false end
					end
				end
			end
			if ok then
				saved[clip] = { Keys = clip.Keys, OffKeys = clip.OffKeys, Both = clip.Both }
				clip.Keys = data.Keys
				if not (opts and opts.LeadOnly) then clip.OffKeys, clip.Both = true, nil end
				on[#on + 1] = name
			else
				warn("[PyroPoseTable] " .. name .. ": the live clip is not the one these keys were made for; left as it is")
			end
		end
	end
	put(T.Clips)
	table.sort(on)
	return on
end

--- Applies the look now and again whenever ReplicatedStorage's PyroLook attribute changes. look() -> "toon" | "flame".
function T.Bind(CastPose, look, opts)
	local function apply()
		T.Apply(CastPose, look(), opts)
	end
	apply()
	return game:GetService("ReplicatedStorage"):GetAttributeChangedSignal("PyroLook"):Connect(apply)
end

return T
