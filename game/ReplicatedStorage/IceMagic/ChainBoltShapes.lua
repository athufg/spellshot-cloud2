	    away = mid - camera.Position, minus its d component;  jog = d:Cross(away.Unit)
	    world(q) = mid + d * ((-q.Z - Length / 2) * Lw / Native) + jog * q.X
	Native is the comic mesh's measured X extent (bolt_family.bolt_mesh built with these arguments, stroke and forks
	included): the drawn outline spans about a to b, as the comic mesh did, and the spine's own ends sit a little inside
	them (by about (Native - Length) / 2 * Lw / Native).

	FORKS. Forks[i].At is the LUA index into Spine of the fork's base (bolt_family's 0-based `at` + 1). Sub is the fork's
	own spine UN-rotated (starting at the origin, running down -Z). The canonical fold, which reproduces
	bolt_family.branch() exactly (the generator checks it):
	    base = Spine[At]; yaw = math.rad(ForkYaw) * (base.X >= 0 and -1 or 1); c, s = math.cos(yaw), math.sin(yaw)
	    point = base + Vector3.new(q.X * c - q.Z * s, 0, q.X * s + q.Z * c)            for each q in Sub
	i.e. the branch always folds back ACROSS the spine (drawn envelope = hit envelope), then is laid like the spine.

	WIDTHS (chain_bolt_bl widths(); per spine point i = 0..n, n = #Spine - 1): Stroke * (1 - (1 - Taper) * i / n), and 0
	at the tip. A fork: Stroke * ForkW, tapering to ForkTaper of itself, 0 at its tip.

	PER-CAST JITTER (chain_bolt_bl.leg_shape(k, jr) with a Random jr): every INTERIOR spine point's x * Jog[1]..Jog[2]
	and its z slid by +-Along x the step (Length / n); the fork's base is that jittered point; each fork's yaw
	ForkYaw +- Jit.ForkYaw degrees, its length x ForkLen[1]..ForkLen[2] -- bolt_spine's z is linear in length and its x
	does not depend on it, so that is Sub's z scaled -- and each of Sub's x * Jog[1]..Jog[2].
